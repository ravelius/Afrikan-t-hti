//
// --- mitä alue EI ole ---
//
// Se ei ole nykyinen puhuma-alue vaan kielten perinteinen kotiseutu.
// Glottolog merkitsee jokaiselle kielelle yhden koordinaatin: espanja
// on Espanjassa, englanti Englannissa, portugali Portugalissa. Siksi
